function pageCopy(page, lang) {
  return {
    ...dictionary.common[lang],
    ...(dictionary[page]?.[lang] || {})
  };
}

function applyLanguage(lang) {
  const nextLang = dictionary.common[lang] ? lang : "zh";
  const page = document.body.dataset.page || "home";
  const copy = pageCopy(page, nextLang);
  document.documentElement.lang = nextLang === "zh" ? "zh-CN" : "en";
  document.body.dataset.lang = nextLang;
  if (copy.pageTitle) document.title = copy.pageTitle;
  const meta = document.querySelector('meta[name="description"]');
  if (meta && copy.metaDescription) meta.setAttribute("content", copy.metaDescription);
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key]) node.textContent = copy[key];
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const key = node.dataset.i18nAlt;
    if (copy[key]) node.setAttribute("alt", copy[key]);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.dataset.i18nAria;
    if (copy[key]) node.setAttribute("aria-label", copy[key]);
  });
  document.querySelectorAll("[data-lang-button]").forEach((button) => {
    const active = button.dataset.langButton === nextLang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  try {
    window.localStorage.setItem("zhongkeintl-lang", nextLang);
  } catch (error) {
    return;
  }
}

document.querySelectorAll("[data-lang-button]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.langButton));
});

let savedLanguage = "zh";
try {
  savedLanguage = window.localStorage.getItem("zhongkeintl-lang") || "zh";
} catch (error) {
  savedLanguage = "zh";
}
applyLanguage(savedLanguage);
